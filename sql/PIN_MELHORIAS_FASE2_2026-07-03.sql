				,ID_REFERENCIA_C
				,ID_REFERENCIA2_C
				,ID_REFERENCIA3_C
				,ID_REFERENCIA4_C
				,ID_REFERENCIA5_C
				,CONSUMO_RACK_COR,COR_A,ID_TIPO_ACABAMENTO,a.ID,NOME
				from PIN_MOV_RECEITAS_LINHAS a
				LEFT JOIN PIN_DIC_TIPO_ACABAMENTO x on a.ID_TIPO_ACABAMENTO = x.ID
				where  ID_RECEITA = @ID_RECEITA and VERSAO = @VERSAO+1
			)a
		) a ) b on a.ID = b.ID

		FETCH NEXT FROM receita_cursor
	INTO @ID_RECEITA,@VERSAO
	END
