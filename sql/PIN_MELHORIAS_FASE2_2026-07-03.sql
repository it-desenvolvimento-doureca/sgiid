				TRY_CONVERT(decimal(19,1),CONSUMO_RACK_COR / NULLIF(CASE WHEN TAXA_MISTURA is null or TAXA_MISTURA = '' then 0 else   CAST(LEFT(REPLACE(TAXA_MISTURA,',','.'), CHARINDEX(':', TAXA_MISTURA) -1 ) as decimal(19,2)) end,0)) CONSUMO_RACK_DILUENTE
				,ID_REFERENCIA_A
